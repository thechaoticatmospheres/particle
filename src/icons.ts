export function elementIcon(kind: string, color: string, size = 28) {
  const p = patterns[kind] ?? patterns.stone;
  let rects = "";
  p.forEach((row, y) =>
    [...row].forEach((v, x) => {
      if (v !== "0")
        rects += `<rect x="${x * 3}" y="${y * 3 + 3}" width="3" height="3" fill="${v === "3" ? "#ffffff" : color}" opacity="${v === "1" ? ".55" : v === "3" ? ".8" : "1"}"/>`;
    }),
  );
  return `<svg class="pixel-icon" width="${size}" height="${size}" viewBox="0 0 24 24" aria-hidden="true">${rects}</svg>`;
}
