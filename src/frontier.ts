// Stable authored discoveries; capabilities also operate independently in the world.
type Entry = {
  id: number;
  base: number;
  pair: [number, number];
  state: Matter;
  color: string;
  description: string;
  traits: Partial<MaterialTraits>;
  lifetime?: number;
};
const row = (
  id: number,
  base: number,
  pair: [number, number],
  state: Matter,
  color: string,
  description: string,
  traits: Partial<MaterialTraits> = {},
  lifetime?: number,
): Entry => ({ id, base, pair, state, color, description, traits, lifetime });
const d = (dynamics: Dynamics): Partial<MaterialTraits> => ({ dynamics });
const melt = (at: number, to: number = E.MoltenMetal) => ({
  heatTransition: { at, to },
});
const fuel = (
  ignition: number,
  duration: number,
  explosive?: number,
): Partial<MaterialTraits> => ({
  ignition,
  fuel: duration,
  explosive,
  defaultMoisture: 0,
});
const gas = (ignition: number, blast: number): Partial<MaterialTraits> => ({
  ...fuel(ignition, 50, blast),
  dynamics: { pressureBurst: 6 },
});
const acid = (strength: number): Partial<MaterialTraits> => ({
  defaultAcidity: strength,
  defaultPollution: 20,
});
const colony = (
  food: NonNullable<Dynamics["colony"]>["food"],
  extra: Partial<Dynamics> = {},
): Partial<MaterialTraits> => ({
  ...d({ colony: { food }, ...extra }),
  defaultMoisture: 55,
});
