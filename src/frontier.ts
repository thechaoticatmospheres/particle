const names = new Map<number, string>(
  Object.entries(E).map(([name, id]) => [
    id,
    name.replace(/([a-z])([A-Z])/g, "$1 $2"),
  ]),
);
export const frontierElements: Element[] = rows.map((r) => ({
  id: r.id,
  name: names.get(r.id)!,
  color: r.color,
  state: r.state,
  density:
    r.state === "gas" || r.state === "energy"
      ? 0
      : r.state === "liquid"
        ? 3
        : r.state === "solid"
          ? 9
          : 5,
  category:
    r.state === "gas"
      ? "Gases"
      : r.state === "liquid"
        ? "Liquids"
        : r.state === "energy" || r.traits.explosive
          ? "Energy"
          : r.base === E.Plant || r.base === E.Wood
            ? "Nature"
            : "Solids",
  icon:
    r.state === "gas"
      ? "steam"
      : r.state === "liquid"
        ? "water"
        : r.state === "energy"
          ? "spark"
          : r.base === E.Plant
            ? "plant"
            : r.base === E.Crystal
              ? "crystal"
              : r.state === "powder"
                ? "sand"
                : "metal",
  description: r.description,
  lifetime: r.lifetime,
}));
